"""Prompt 模板 — 不同辩论阶段的 System Prompt 和 User Prompt"""

# ============================================================
# 角色推荐 Prompt
# ============================================================

ROLE_RECOMMEND_PROMPT = """你是一个辩论策划专家。用户将给你一个辩论话题，你需要推荐 3-5 个适合讨论该话题的角色。

要求：
1. 每个角色有独特的专业视角和立场倾向
2. 角色之间应该能形成观点的碰撞和互补
3. 返回 JSON 数组格式，每个元素包含 name、role、stance 三个字段

话题：{topic}

只返回 JSON 数组，不要其他内容。示例格式：
[{{"name": "经济学家", "role": "你是一位自由市场经济学家，相信市场自我调节的力量...", "stance": "支持自由市场"}}, ...]
"""

# ============================================================
# 辩论轮次 Prompt
# ============================================================

ROUND_OPENING = """## 第 {round_num}/{total_rounds} 轮 — 开场陈述

作为 {agent_name}，请发表你的开场陈述：
- 清晰地阐述你对「{topic}」的核心观点
- 提供 2-3 个关键论据支撑你的立场
- 注意你已经看到的其他辩手发言，可以简要回应
- 保持 {stance} 的立场
- 控制在 300 字以内"""

ROUND_REBUTTAL = """## 第 {round_num}/{total_rounds} 轮 — 自由辩论

作为 {agent_name}，现在是自由辩论环节。回顾之前的讨论：

{debate_history}

请针对性地发言：
- 直接回应和反驳与你立场不同的观点（必须指明对方名字）
- 强化你自己之前提出的论据
- 如果发现对方逻辑漏洞，请明确指出
- 保持 {stance} 的立场
- 控制在 300 字以内"""

ROUND_CLOSING = """## 第 {round_num}/{total_rounds} 轮 — 总结陈词

作为 {agent_name}，这是最后一轮。请做总结陈词：

{debate_history}

要求：
- 总结全场辩论的关键分歧点
- 重申你的核心立场和最强论据
- 指出对方观点中你认同的部分（如有）
- 给出最终结论
- 控制在 300 字以内"""
