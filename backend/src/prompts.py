"""Prompt 模板 — 不同辩论阶段的 System Prompt 和 User Prompt"""

# ============================================================
# 角色推荐 Prompt
# ============================================================

ROLE_RECOMMEND_PROMPT = """你是一个辩论策划专家。用户将给你一个辩论话题，你需要推荐 3-5 个适合讨论该话题的角色。

要求：
1. 每个角色有独特的专业视角和立场倾向
2. 角色之间应该能形成观点的碰撞和互补
3. 返回 JSON 数组格式，每个元素包含 name、role、stance 三个字段

话题：{topic}

只返回 JSON 数组，不要其他内容。示例格式：
[{{"name": "经济学家", "role": "你是一位自由市场经济学家，相信市场自我调节的力量...", "stance": "支持自由市场"}}, ...]
"""

# ============================================================
# 辩论轮次 Prompt
# ============================================================

ROUND_OPENING = """## 第 {round_num}/{total_rounds} 轮 — 开场陈述

作为 {agent_name}，请发表你的开场陈述：
- 清晰地阐述你对「{topic}」的核心观点
- 提供 2-3 个关键论据支撑你的立场
- 注意你已经看到的其他辩手发言，可以简要回应
- 保持 {stance} 的立场
- 控制在 300 字以内"""

ROUND_REBUTTAL = """## 第 {round_num}/{total_rounds} 轮 — 自由辩论

作为 {agent_name}，现在是自由辩论环节。回顾之前的讨论：

{debate_history}

请针对性地发言：
- 直接回应和反驳与你立场不同的观点（必须指明对方名字）
- 强化你自己之前提出的论据
- 如果发现对方逻辑漏洞，请明确指出
- 保持 {stance} 的立场
- 控制在 300 字以内"""

ROUND_CLOSING = """## 第 {round_num}/{total_rounds} 轮 — 总结陈词

作为 {agent_name}，这是最后一轮。请做总结陈词：

{debate_history}

要求：
- 总结全场辩论的关键分歧点
- 重申你的核心立场和最强论据
- 指出对方观点中你认同的部分（如有）
- 给出最终结论
- 控制在 300 字以内"""

# ============================================================
# 事实核查 Prompt — 多 Agent 文本审查
# ============================================================

FACT_CHECK_SYSTEM = """你是一位专业的{role}。你的任务是对用户提供的文本进行严格审查，从你的专业角度发现所有可能的问题。

## 审查文本
{text}

## 审查规则
1. 逐句分析文本中的每一个陈述
2. 标记出任何事实性错误、逻辑漏洞、时间矛盾、数据失实、AI 模式化表达
3. 对每个问题点给出具体引文和解释
4. 如果有不确定的地方，明确标注"存疑"而非断言错误
5. 用中文输出"""

FACT_CHECK_OPENING = """## 第一轮 — 独立审查

请从你的专业角度（{stance}），逐条列出你发现的文本问题。

格式要求：
- 每个问题一行，格式：【问题类型】问题描述 — 涉及原文："……"
- 如果文本某处完全无误，也请说明"未发现问题"
- 不要遗漏任何可疑之处"""

FACT_CHECK_DEBATE = """## 第二轮 — 交叉辩论

以下是其他审查员的发现：

{other_findings}

请你：
1. 对其他人标记的问题发表看法（同意/反对/补充证据）
2. 如果别人对你之前标记的问题有异议，请回应
3. 合并重复的问题
4. 最终给出你确认的问题清单

输出格式：
### 确认的问题
- 【问题类型】描述 — 原文出处

### 与他人有分歧的问题
- 你的立场 + 理由"""

FACT_CHECK_JUDGE = """## 裁判总结

你是一位公正的裁判。以下是全部审查员的最终意见和辩论记录：

{all_findings}

请你整合所有意见，输出最终审查报告：

### 严重问题（事实错误/逻辑矛盾）
- 问题描述 + 多方共识

### 存疑问题（证据不足/需要进一步核实）
- 问题描述 + 分歧点

### AI 模式化特征
- 检测到的 AI 写作痕迹

### 总体评分
- 事实准确度：X/10
- 逻辑严谨度：X/10
- 时间线清晰度：X/10

### 总结建议"""
